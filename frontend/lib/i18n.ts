/** Polish: 1 danie, 2–4 dania, 5+ dań (12–14 take the "many" form). */
function plPlural(n: number, one: string, few: string, many: string): string {
  if (n === 1) return one;
  const tens = n % 100;
  return n % 10 >= 2 && n % 10 <= 4 && (tens < 12 || tens > 14) ? few : many;
}

/** Ukrainian: like Polish, except 21, 31… take the "one" form too. */
function ukPlural(n: number, one: string, few: string, many: string): string {
  const tens = n % 100;
  if (n % 10 === 1 && tens !== 11) return one;
  return n % 10 >= 2 && n % 10 <= 4 && (tens < 12 || tens > 14) ? few : many;
}

